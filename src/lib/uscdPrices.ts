function normalize(sku: string): string {
  return sku.toUpperCase().replace(/\s+/g, '');
}

const NORMALIZED: Record<string, (number | null)[]> = {};
const LOOSE: Record<string, (number | null)[]> = {};
for (const [sku, prices] of Object.entries(USCD_LIST_PRICES)) {
  NORMALIZED[normalize(sku)] = prices;
  LOOSE[normalize(sku).replace(/[^A-Z0-9]/g, '')] = prices;
}

/** Look up the list price for a SKU under the given door style code. */
export function getListPrice(sku: string, doorStyleCode: string): number | null {
  const style = USCD_DOOR_STYLES.find(s => s.code === doorStyleCode);
  if (!style || !sku) return null;
  const key = normalize(sku);
  const prices = NORMALIZED[key] ?? LOOSE[key.replace(/[^A-Z0-9]/g, '')];
  if (!prices) return null;
  const price = prices[style.tier];
  return typeof price === 'number' ? price : null;
}

export function hasListPrice(sku: string): boolean {
  const key = normalize(sku);
  return Boolean(NORMALIZED[key] ?? LOOSE[key.replace(/[^A-Z0-9]/g, '')]);
}

/** All US Cabinet Depot SKU codes in the price book (uppercase, as printed). */
export const USCD_CATALOG_SKUS: string[] = Object.keys(USCD_LIST_PRICES).map(s => s.toUpperCase().trim());
